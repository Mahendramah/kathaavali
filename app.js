const dialog = document.querySelector('#story-reader');
const readerTitle = document.querySelector('#reader-title');
const readerCategory = document.querySelector('#reader-category');
const readerBody = document.querySelector('#reader-body');

function openStory(id) {
  const story = stories[id];
  if (!story) return;
  readerTitle.textContent = story.title;
  readerCategory.textContent = story.category;
  readerBody.replaceChildren(...story.body.map(text => {
    const paragraph = document.createElement('p');
    paragraph.textContent = text;
    return paragraph;
  }));
  dialog.showModal();
  document.body.style.overflow = 'hidden';
}

document.querySelectorAll('.read-story').forEach(button => {
  button.addEventListener('click', () => openStory(button.dataset.story));
});

function closeReader() { dialog.close(); document.body.style.overflow = ''; }
document.querySelector('.close-reader').addEventListener('click', closeReader);
dialog.addEventListener('click', event => { if (event.target === dialog) closeReader(); });
dialog.addEventListener('close', () => { document.body.style.overflow = ''; });

const filters = document.querySelectorAll('.filter');
const cards = document.querySelectorAll('.story-card');
const search = document.querySelector('#story-search');
const noResults = document.querySelector('.no-results');
let activeFilter = 'all';

function filterStories() {
  const query = search.value.trim().toLowerCase();
  let count = 0;
  cards.forEach(card => {
    const matchingCategory = activeFilter === 'all' || card.dataset.category === activeFilter;
    const matchingSearch = card.dataset.search.toLowerCase().includes(query);
    const show = matchingCategory && matchingSearch;
    card.hidden = !show;
    if (show) count += 1;
  });
  noResults.hidden = count !== 0;
}
filters.forEach(filter => filter.addEventListener('click', () => {
  activeFilter = filter.dataset.filter;
  filters.forEach(item => item.classList.toggle('active', item === filter));
  filterStories();
}));
search.addEventListener('input', filterStories);

